require('dotenv').config({ path: '.env.local' });
const https = require('https');

const supabaseUrl = process.env.NEXT_PUBLIC_SUPABASE_URL || '';
const serviceKey = process.env.SUPABASE_SERVICE_ROLE_KEY || '';

if (!supabaseUrl || !serviceKey) {
  console.error('Missing NEXT_PUBLIC_SUPABASE_URL or SUPABASE_SERVICE_ROLE_KEY in .env.local');
  process.exit(1);
}

const projectRef = supabaseUrl.match(/https:\/\/([^.]+)\.supabase\.co/)[1];

console.log('Project ref:', projectRef);
console.log('Cleaning up Oasis International School - PASS 2\n');

function api(path, method = 'GET', body = null) {
  return new Promise((resolve, reject) => {
    const options = {
      hostname: projectRef + '.supabase.co',
      path,
      method,
      headers: { apikey: serviceKey, Authorization: 'Bearer ' + serviceKey }
    };
    if (body !== null) {
      options.headers['Content-Type'] = 'application/json';
      options.headers['Content-Length'] = Buffer.byteLength(JSON.stringify(body));
    }
    const req = https.request(options, (res) => {
      let data = '';
      res.on('data', (chunk) => data += chunk);
      res.on('end', () => {
        try {
          resolve({ status: res.statusCode, body: data ? JSON.parse(data) : null });
        } catch (e) {
          resolve({ status: res.statusCode, body: data });
        }
      });
    });
    req.on('error', reject);
    if (body !== null) req.write(JSON.stringify(body));
    req.end();
  });
}

async function getAllUsers() {
  const perPage = 1000;
  let all = [];
  let page = 0;
  while (true) {
    const path = `/rest/v1/users?select=id,email,name,created_at,role,institution_name&role=eq.individual&institution_name=ilike.*Oasis%20International%20School*&order=created_at.desc&limit=${perPage}&offset=${page * perPage}`;
    const { body, status } = await api(path);
    if (status !== 200 || !Array.isArray(body) || body.length === 0) break;
    all = all.concat(body);
    if (body.length < perPage) break;
    page++;
  }
  return all;
}

async function countAssessments(uuid) {
  const { body, status } = await api(`/rest/v1/assessment_results?user_id=eq.${encodeURIComponent(uuid)}&select=id`);
  if (status !== 200 || !Array.isArray(body)) return 0;
  return body.length;
}

function isAutoGenerated(email) {
  return /^student\d+@mentormeright\.com$/i.test(String(email || ''));
}

function normalizeName(name) {
  return String(name || '')
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9\s]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

async function main() {
  const users = await getAllUsers();
  console.log(`Total users at Oasis: ${users.length}\n`);

  // --- Phase 1: Delete standalone auto-generated student@ emails ---
  const autoGenUsers = users.filter(u => isAutoGenerated(u.email));
  console.log(`Auto-generated (student@) emails found: ${autoGenUsers.length}`);

  // Build name map to check if a real-email counterpart exists
  const nameGroups = {};
  for (const u of users) {
    const normName = normalizeName(u.name);
    if (!normName) continue;
    if (!nameGroups[normName]) nameGroups[normName] = [];
    nameGroups[normName].push(u);
  }

  // Find name groups with multiple users (some auto-gen, some real)
  const dupNameGroups = Object.entries(nameGroups).filter(
    ([, g]) => g.length > 1 && new Set(g.map(u => (u.email||'').toLowerCase().trim())).size > 1
  );
  console.log(`Name groups with duplicates: ${dupNameGroups.length}\n`);

  // Build set of auto-gen user IDs to delete (those that don't have completed tests)
  const idsToDelete = new Set();

  console.log('=== Auto-generated emails to DELETE (no completed tests) ===');
  for (const dupe of autoGenUsers) {
    const count = await countAssessments(dupe.id);
    if (count > 0) {
      console.log(`  SKIP (has ${count} completed test(s)): ${dupe.name} <${dupe.email}>`);
    } else {
      console.log(`  DELETE: ${dupe.name} <${dupe.email}>`);
      idsToDelete.add(dupe.id);
    }
  }

  // --- Phase 2: Handle remaining name-based duplicate groups ---
  // (both non-auto-gen, one has tests → skip it, delete the other if no tests)
  console.log('\n=== Remaining duplicate groups (same name, both non-auto-gen) ===');
  for (const [name, group] of dupNameGroups) {
    const autoGenInGroup = group.filter(u => isAutoGenerated(u.email));
    const realEmails = group.filter(u => !isAutoGenerated(u.email));

    // If group has auto-gen users, they're already handled in Phase 1
    if (autoGenInGroup.length > 0) {
      // Skip - these will be handled by Phase 1
      // But check: is there a real-email user with tests in this group? Keep them.
      continue;
    }

    // All real emails - find which has completed tests
    let keepId = null;
    let deleteId = null;
    for (const u of group) {
      const count = await countAssessments(u.id);
      if (count > 0) {
        console.log(`  KEEP (has ${count} completed tests): ${u.name} <${u.email}>`);
        keepId = u.id;
      } else {
        console.log(`  CANDIDATE FOR DELETE: ${u.name} <${u.email}>`);
        deleteId = u.id;
      }
    }
    // If we have both a keep and delete candidate, delete the one without tests
    if (keepId && deleteId && !idsToDelete.has(deleteId) && !idsToDelete.has(keepId)) {
      console.log(`    -> DELETE the one without tests: id=${deleteId}`);
      idsToDelete.add(deleteId);
    }
  }

  console.log(`\nTotal IDs to delete: ${idsToDelete.size}`);
  console.log('Executing deletions...\n');

  let deleted = 0;
  let skipped = 0;
  let errors = 0;

  for (const dupeId of Array.from(idsToDelete)) {
    const user = users.find(u => u.id === dupeId);
    const count = await countAssessments(dupeId);
    if (count > 0) {
      console.log(`SKIP (has ${count} completed test(s)): ${user?.name} <${user?.email}>`);
      skipped++;
      continue;
    }

    console.log(`DELETE: ${user?.name} <${user?.email}> id=${dupeId}`);

    const url = new URL('/auth/v1/admin/users/' + encodeURIComponent(dupeId), 'https://' + projectRef + '.supabase.co');
    const authResult = await api(url.pathname, 'DELETE');
    const pubResult = await api(`/rest/v1/users?id=eq.${encodeURIComponent(dupeId)}`, 'DELETE');

    if (authResult.status === 200 || authResult.status === 204) {
      deleted++;
    } else {
      console.error(`  ERROR: auth=${authResult.status} public=${pubResult.status}`);
      errors++;
    }
  }

  console.log(`\n=== SUMMARY ===`);
  console.log(`Total users scanned: ${users.length}`);
  console.log(`Users deleted: ${deleted}`);
  console.log(`Users skipped (had completed tests): ${skipped}`);
  console.log(`Errors: ${errors}`);
  console.log(`\nCompleted tests were NOT touched.`);
}

main().catch(err => console.error('Script error:', err));
