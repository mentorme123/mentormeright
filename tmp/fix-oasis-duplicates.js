require('dotenv').config({ path: '.env.local' });
const https = require('https');

const supabaseUrl = process.env.NEXT_PUBLIC_SUPABASE_URL || '';
const serviceKey = process.env.SUPABASE_SERVICE_ROLE_KEY || '';

if (!supabaseUrl || !serviceKey) {
  console.error('Missing NEXT_PUBLIC_SUPABASE_URL or SUPABASE_SERVICE_ROLE_KEY in .env.local');
  process.exit(1);
}

// Extract project ref (e.g. "fszbbmbaoqigotemhkda") from the URL
let projectRef;
try {
  const m = supabaseUrl.match(/https:\/\/([^.]+)\.supabase\.co/);
  projectRef = m[1];
} catch {
  console.error('Could not parse project ref from NEXT_PUBLIC_SUPABASE_URL:', supabaseUrl);
  process.exit(1);
}

console.log('Project ref:', projectRef);
console.log('Scanning Oasis International School...\n');

function api(path, method = 'GET', body = null) {
  return new Promise((resolve, reject) => {
    const options = {
      hostname: projectRef + '.supabase.co',
      path,
      method,
      headers: { apikey: serviceKey, Authorization: 'Bearer ' + serviceKey }
    };
    if (body !== null) {
      options.headers['Content-Type'] = 'application/json';
      options.headers['Content-Length'] = Buffer.byteLength(JSON.stringify(body));
    }
    const req = https.request(options, (res) => {
      let data = '';
      res.on('data', (chunk) => data += chunk);
      res.on('end', () => {
        try {
          resolve({ status: res.statusCode, body: data ? JSON.parse(data) : null });
        } catch (e) {
          resolve({ status: res.statusCode, body: data });
        }
      });
    });
    req.on('error', reject);
    if (body !== null) req.write(JSON.stringify(body));
    req.end();
  });
}

async function getAllUsers() {
  const perPage = 1000;
  let all = [];
  let page = 0;
  while (true) {
    const path = `/rest/v1/users?select=id,email,name,created_at,role,institution_name&role=eq.individual&institution_name=ilike.*Oasis%20International%20School*&order=created_at.desc&limit=${perPage}&offset=${page * perPage}`;
    const { body, status } = await api(path);
    if (status !== 200 || !Array.isArray(body) || body.length === 0) break;
    all = all.concat(body);
     if (body.length < perPage) break;
    page++;
  }
  return all;
}

async function countAssessments(uuid) {
  const { body, status } = await api(`/rest/v1/assessment_results?user_id=eq.${encodeURIComponent(uuid)}&select=id`);
  if (status !== 200 || !Array.isArray(body)) return 0;
  return body.length;
}

function isAutoGenerated(email) {
  return /^student\d+@mentormeright\.com$/i.test(String(email || ''));
}

function normalizeName(name) {
  return String(name || '')
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9\s]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

async function main() {
  const users = await getAllUsers();
  console.log(`Total users with institution="Oasis International School": ${users.length}\n`);

  // --- Build email-based duplicate groups ---
  const emailGroups = {};
  for (const u of users) {
    const key = String(u.email || '').toLowerCase().trim();
    if (!key) continue;
    if (!emailGroups[key]) emailGroups[key] = [];
    emailGroups[key].push(u);
  }

  // --- Build name-based duplicate groups (same name, different emails) ---
  const nameGroups = {};
  for (const u of users) {
    const normName = normalizeName(u.name);
    if (!normName) continue;
    if (!nameGroups[normName]) nameGroups[normName] = [];
    nameGroups[normName].push(u);
  }

  // Collect IDs to remove and IDs to keep
  // Strategy: keep the user with completed tests; prefer the user with a real (non-auto-gen) email
  const idsToRemove = new Set();
  const idsToKeep = new Set();

  console.log('=== Email-based duplicate groups ===');
  for (const [email, group] of Object.entries(emailGroups)) {
    if (group.length <= 1) continue;
    // Sort: prefer non-auto-gen email (keep real email, delete student1768@)
    group.sort((a, b) => {
      const aAuto = isAutoGenerated(a.email) ? 1 : 0;
      const bAuto = isAutoGenerated(b.email) ? 1 : 0;
      if (aAuto !== bAuto) return aAuto - bAuto; // non-auto-gen first
      // Then prefer newest (real email import is usually newer)
      const ta = a.created_at ? new Date(a.created_at).getTime() : 0;
      const tb = b.created_at ? new Date(b.created_at).getTime() : 0;
      return tb - ta; // newest first
    });
    const [keep, ...duplicates] = group;
    idsToKeep.add(keep.id);
    for (const d of duplicates) idsToRemove.add(d.id);
    console.log(`Email: ${email}`);
    console.log(`  KEEP: ${keep.name} <${keep.email}>`);
    for (const d of duplicates) console.log(`  REMOVE: ${d.name} <${d.email}>`);
  }

  console.log('\n=== Name-based duplicate groups (same name, different emails) ===');
  const processedNames = new Set();
  for (const [name, group] of Object.entries(nameGroups)) {
    if (group.length <= 1) continue;
    const uniqueEmails = new Set(group.map(u => String(u.email || '').toLowerCase().trim()));
    if (uniqueEmails.size <= 1) continue; // already handled by email dedup
    if (processedNames.has(name)) continue;
    processedNames.add(name);

    // Sort: prefer non-auto-gen email (keep real email, delete student1768@)
    group.sort((a, b) => {
      const aAuto = isAutoGenerated(a.email) ? 1 : 0;
      const bAuto = isAutoGenerated(b.email) ? 1 : 0;
      if (aAuto !== bAuto) return aAuto - bAuto;
      const ta = a.created_at ? new Date(a.created_at).getTime() : 0;
      const tb = b.created_at ? new Date(b.created_at).getTime() : 0;
      return tb - ta;
    });
    const [keep, ...duplicates] = group;
    if (!idsToKeep.has(keep.id)) idsToKeep.add(keep.id);
    for (const d of duplicates) idsToRemove.add(d.id);
    console.log(`Name: "${keep.name}"`);
    console.log(`  KEEP: <${keep.email}>`);
    for (const d of duplicates) console.log(`  REMOVE: <${d.email}>`);
  }

  // Remove any IDs from idsToRemove that are also in idsToKeep
  for (const id of idsToKeep) {
    if (idsToRemove.has(id)) {
      idsToRemove.delete(id);
      console.log(`\nNOTE: id=${id} was marked for removal but also for keep — keeping it.`);
    }
  }

  console.log(`\nTotal IDs to remove: ${idsToRemove.size}`);
  console.log(`Total IDs to keep:   ${idsToKeep.size}\n`);

  let deleted = 0;
  let skippedWithTests = 0;
  let errors = 0;

  for (const dupeId of Array.from(idsToRemove)) {
    // Check if this user has completed assessments
    const assessmentCount = await countAssessments(dupeId);

    if (assessmentCount > 0) {
      const user = users.find(u => u.id === dupeId);
      console.log(`SKIP (has ${assessmentCount} completed test(s)): ${user?.name} <${user?.email}> id=${dupeId}`);
      console.log(`  -> NOT deleting, NOT touching completed tests`);
      skippedWithTests++;
      continue;
    }

    const user = users.find(u => u.id === dupeId);
    console.log(`DELETE: ${user?.name} <${user?.email}> id=${dupeId}`);

    // Delete from auth.users via Admin API
    const url = new URL('/auth/v1/admin/users/' + encodeURIComponent(dupeId), 'https://' + projectRef + '.supabase.co');
    const authStatus = await api(url.pathname, 'DELETE');

    // Delete from public.users
    const pubResult = await api(`/rest/v1/users?id=eq.${encodeURIComponent(dupeId)}`, 'DELETE');

    if (authStatus.status === 200 || authStatus.status === 204) {
      deleted++;
      console.log(`  -> Deleted (auth + public)`);
    } else {
      console.error(`  -> ERROR: auth=${authStatus.status} public=${pubResult.status}`);
      errors++;
    }
  }

  console.log(`\n=== SUMMARY ===`);
  console.log(`Total users scanned: ${users.length}`);
  console.log(`Users deleted: ${deleted}`);
  console.log(`Users skipped (had completed tests): ${skippedWithTests}`);
  console.log(`Users kept: ${users.length - deleted - skippedWithTests}`);
  console.log(`Errors: ${errors}`);
  console.log(`\nCompleted tests were NOT touched — users with completed assessments were skipped.`);

  return { deleted, skippedWithTests, errors };
}

main().catch(err => console.error('Script error:', err));
